def simulated_columns_caption(frame: pd.DataFrame) -> None:
    """Name the simulated columns of a table under the table.

    The `sim_` prefix is on every column header already (§3.2). This restates it
    as a sentence because a reader scanning a wide table reads the values, not the
    headers, and "seven of these fourteen columns describe events that never
    happened" is the thing they need.
    """
    from src.demo import spec

    simulated = spec.simulated_columns(list(frame.columns))
    if not simulated:
        st.caption("No `sim_` columns in this table.")
        return
    st.caption(
        f"**{len(simulated)} of {frame.shape[1]} columns are SIMULATED** "
        f"(`{'`, `'.join(simulated)}`) — generated by this project's simulation layer, "
        "not measured from anything."
    )


def dataframe(frame: pd.DataFrame, **kwargs: Any) -> None:
    """A table plus its simulated-column caption. Always both."""
    st.dataframe(frame, width="stretch", hide_index=True, **kwargs)
    simulated_columns_caption(frame)


def money(value: float) -> str:
    return f"${value:,.0f}"


def percent(value: float, digits: int = 1) -> str:
    return f"{value * 100:.{digits}f}%"
