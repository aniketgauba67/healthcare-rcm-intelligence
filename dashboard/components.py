"""Shared UI, and the one component CLAUDE.md §6 makes non-optional.

**Every page renders `render_synthetic_data_banner()`. No page ships without it.**
That is §6 verbatim, and §3.5 is why it is absolute rather than a nicety: Medicare
fee-for-service has exactly ONE payer and our payer dimension is 100% simulated,
so a payer comparison without the banner is a comparison of five payers that do
not exist. `tests/contracts/test_dashboard_banner.py` (qa's) fails the build for
any page module that renders content without calling it.

The banner is a component and not a copied paragraph for the same reason
`dashboard/disclosures.py` exists: five pages retyping a disclosure is five
chances for one of them to be softer than the others, and the soft one is the one
a reader will quote back.

EVERY FIGURE ON EVERY PAGE CARRIES ITS PROVENANCE
--------------------------------------------------
`kpi_row` takes a classification per metric — SOURCE, DERIVED, REFERENCE or
SIMULATED (§3.1) — and prints it under the number. A dashboard is the surface most
likely to launder a simulated dollar into a real one, because a big styled metric
tile reads as a fact about the world. The class under it is what stops that, and
it is a required argument rather than an optional one so a tile cannot ship
without a decision having been made about it.

`control_query` prints the SQL a figure must reconcile to, right beside the
figure. §7 requires dashboard totals to reconcile to SQL control queries; showing
the query where the number is means a reader can check it instead of trusting it.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Literal

import altair as alt
import pandas as pd
import streamlit as st

from dashboard import disclosures
from dashboard.provenance import DashboardEmitter

Classification = Literal["SOURCE", "DERIVED", "REFERENCE", "SIMULATED", "MIXED"]

#: What each provenance class means in one line, shown on hover. Wording is the
#: §3.1 wording, not a paraphrase.
_CLASS_HELP: dict[str, str] = {
    "SOURCE": "From the official CMS synthetic claim files, unmodified.",
    "DERIVED": "Computed from SOURCE fields by this project's warehouse.",
    "REFERENCE": "From an official published code or facility reference file.",
    "SIMULATED": "Generated by THIS PROJECT'S simulation layer. Not a real outcome.",
    "MIXED": "Combines SOURCE, DERIVED and SIMULATED inputs — see the note below.",
}

_CLASS_BADGE: dict[str, str] = {
    "SOURCE": ":blue-badge[SOURCE]",
    "DERIVED": ":violet-badge[DERIVED]",
    "REFERENCE": ":green-badge[REFERENCE]",
    "SIMULATED": ":red-badge[SIMULATED]",
    "MIXED": ":orange-badge[MIXED]",
}


